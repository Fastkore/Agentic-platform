import {
  AbortMultipartUploadCommand, CompleteMultipartUploadCommand, CreateBucketCommand, CreateMultipartUploadCommand, DeleteObjectCommand,
  GetObjectCommand, HeadBucketCommand, HeadObjectCommand, ListObjectsV2Command, PutObjectCommand, S3Client, S3ServiceException, UploadPartCommand,
} from '@aws-sdk/client-s3';
import { randomUUID } from 'node:crypto';
import { createReadStream, createWriteStream, readFileSync } from 'node:fs';
import { mkdir, open, readdir, rm, stat, unlink, writeFile, rename } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { BridgeError } from '../store.js';

/** Internal object keys are generated by the server only: sources/<sourceId>/blobs/<blobId>. */
const keyPattern = /^sources\/[A-Za-z0-9_-]{1,80}\/blobs\/[A-Za-z0-9_-]{1,80}$/;
export function blobKey(sourceId: string, blobId: string) {
  const key = `sources/${sourceId}/blobs/${blobId}`;
  if (!keyPattern.test(key)) throw new Error('Invalid source object key');
  return key;
}
function checkKey(key: string) { if (!keyPattern.test(key)) throw new Error('Invalid source object key'); }

export interface SourceBlobStore {
  readonly kind: 's3' | 'filesystem-dev';
  check(): Promise<void>;
  put(key: string, body: Buffer): Promise<void>;
  createMultipart(key: string): Promise<string>;
  uploadPart(key: string, uploadId: string, partNumber: number, body: Buffer): Promise<string>;
  completeMultipart(key: string, uploadId: string, parts: { partNumber: number; etag: string }[]): Promise<void>;
  abortMultipart(key: string, uploadId: string): Promise<void>;
  head(key: string): Promise<{ size: number } | undefined>;
  stream(key: string, signal?: AbortSignal, start?: number): Promise<Readable>;
  delete(key: string): Promise<void>;
  list(prefix: string): AsyncIterable<{ key: string; size: number }>;
  close(): void;
}

const unavailable = () => new BridgeError('Хранилище источников временно недоступно.', 503);
const s3Status = (error: unknown) => error instanceof S3ServiceException ? error.$metadata.httpStatusCode : undefined;

export class S3SourceBlobStore implements SourceBlobStore {
  readonly kind = 's3' as const;
  private readonly client: S3Client;
  constructor(private readonly bucket: string, options: { endpoint?: string; region: string; accessKeyId: string; secretAccessKey: string; forcePathStyle: boolean },
    private readonly createBucket = false) {
    this.client = new S3Client({
      endpoint: options.endpoint, region: options.region, forcePathStyle: options.forcePathStyle,
      credentials: { accessKeyId: options.accessKeyId, secretAccessKey: options.secretAccessKey }, maxAttempts: 3,
      requestChecksumCalculation: 'WHEN_REQUIRED', responseChecksumValidation: 'WHEN_REQUIRED',
    });
  }
  private async send<T>(command: object, timeout = 30_000, signal?: AbortSignal): Promise<T> {
    const abortSignal = signal ? AbortSignal.any([signal, AbortSignal.timeout(timeout)]) : AbortSignal.timeout(timeout);
    const send = this.client.send.bind(this.client) as unknown as (command: object, options: { abortSignal: AbortSignal }) => Promise<T>;
    return send(command, { abortSignal });
  }
  async check() {
    try {
      try { await this.send(new HeadBucketCommand({ Bucket: this.bucket }), 15_000); }
      catch (error) {
        if (!this.createBucket || s3Status(error) !== 404) throw error;
        await this.send(new CreateBucketCommand({ Bucket: this.bucket }), 15_000);
      }
    } catch { throw new BridgeError('Не удалось подключиться к бакету источников. Проверьте настройки сервера.', 503); }
  }
  async put(key: string, body: Buffer) {
    checkKey(key);
    try { await this.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: 'application/octet-stream' }), 120_000); }
    catch { throw unavailable(); }
  }
  async createMultipart(key: string) {
    checkKey(key);
    try {
      const result = await this.send<{ UploadId?: string }>(new CreateMultipartUploadCommand({ Bucket: this.bucket, Key: key, ContentType: 'application/octet-stream' }));
      if (!result.UploadId) throw new Error('missing upload id');
      return result.UploadId;
    } catch { throw unavailable(); }
  }
  async uploadPart(key: string, uploadId: string, partNumber: number, body: Buffer) {
    checkKey(key);
    try {
      const result = await this.send<{ ETag?: string }>(new UploadPartCommand({ Bucket: this.bucket, Key: key, UploadId: uploadId, PartNumber: partNumber, Body: body }), 120_000);
      if (!result.ETag) throw new Error('missing etag');
      return result.ETag;
    } catch { throw unavailable(); }
  }
  async completeMultipart(key: string, uploadId: string, parts: { partNumber: number; etag: string }[]) {
    checkKey(key);
    try {
      await this.send(new CompleteMultipartUploadCommand({ Bucket: this.bucket, Key: key, UploadId: uploadId,
        MultipartUpload: { Parts: parts.map(p => ({ PartNumber: p.partNumber, ETag: p.etag })) } }), 120_000);
    } catch { throw unavailable(); }
  }
  async abortMultipart(key: string, uploadId: string) {
    checkKey(key);
    try { await this.send(new AbortMultipartUploadCommand({ Bucket: this.bucket, Key: key, UploadId: uploadId })); }
    catch (error) { if (s3Status(error) !== 404) throw unavailable(); }
  }
  async head(key: string) {
    checkKey(key);
    try {
      const result = await this.send<{ ContentLength?: number }>(new HeadObjectCommand({ Bucket: this.bucket, Key: key }), 15_000);
      return { size: result.ContentLength ?? 0 };
    } catch (error) {
      if (s3Status(error) === 404 || (error as { name?: string }).name === 'NotFound') return undefined;
      throw unavailable();
    }
  }
  async stream(key: string, signal?: AbortSignal, start?: number) {
    checkKey(key);
    try {
      const result = await this.send<{ Body?: unknown }>(new GetObjectCommand({ Bucket: this.bucket, Key: key, Range: start ? `bytes=${start}-` : undefined }), 300_000, signal);
      if (!(result.Body instanceof Readable)) throw new Error('unexpected body');
      return result.Body;
    } catch (error) {
      signal?.throwIfAborted();
      if (s3Status(error) === 404) throw new BridgeError('Объект источника не найден.', 404);
      throw unavailable();
    }
  }
  async delete(key: string) {
    checkKey(key);
    try { await this.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key })); } catch { throw unavailable(); }
  }
  async *list(prefix: string) {
    let token: string | undefined;
    do {
      const page = await this.send<{ Contents?: { Key?: string; Size?: number }[]; NextContinuationToken?: string; IsTruncated?: boolean }>(
        new ListObjectsV2Command({ Bucket: this.bucket, Prefix: prefix, ContinuationToken: token }));
      for (const item of page.Contents ?? []) if (item.Key) yield { key: item.Key, size: item.Size ?? 0 };
      token = page.IsTruncated ? page.NextContinuationToken : undefined;
    } while (token);
  }
  close() { this.client.destroy(); }
}

/** Development and test driver. Refused when NODE_ENV=production; production uses a private S3 bucket. */
export class FilesystemSourceBlobStore implements SourceBlobStore {
  readonly kind = 'filesystem-dev' as const;
  constructor(private readonly root: string) {}
  private file(key: string) { checkKey(key); return path.join(this.root, ...key.split('/')); }
  private partDir(uploadId: string) {
    if (!/^[a-f0-9-]{36}$/.test(uploadId)) throw new Error('Invalid upload id');
    return path.join(this.root, '.multipart', uploadId);
  }
  async check() { await mkdir(this.root, { recursive: true, mode: 0o700 }); }
  async put(key: string, body: Buffer) {
    const target = this.file(key), temp = target + '.' + randomUUID() + '.tmp';
    await mkdir(path.dirname(target), { recursive: true, mode: 0o700 });
    await writeFile(temp, body, { mode: 0o600 }); await rename(temp, target);
  }
  async createMultipart(key: string) { this.file(key); const id = randomUUID(); await mkdir(this.partDir(id), { recursive: true, mode: 0o700 }); return id; }
  async uploadPart(key: string, uploadId: string, partNumber: number, body: Buffer) {
    this.file(key);
    await writeFile(path.join(this.partDir(uploadId), String(partNumber)), body, { mode: 0o600 });
    return '"' + partNumber + '-' + body.length + '"';
  }
  async completeMultipart(key: string, uploadId: string, parts: { partNumber: number; etag: string }[]) {
    const target = this.file(key), temp = target + '.' + randomUUID() + '.tmp';
    await mkdir(path.dirname(target), { recursive: true, mode: 0o700 });
    const directory = this.partDir(uploadId);
    async function* content() {
      for (const part of [...parts].sort((a, b) => a.partNumber - b.partNumber)) {
        yield* createReadStream(path.join(directory, String(part.partNumber)));
      }
    }
    try {
      await pipeline(content(), createWriteStream(temp, { flags: 'wx', mode: 0o600 }));
      await rename(temp, target);
    } catch (error) {
      await rm(temp, { force: true }).catch(() => {});
      throw error;
    }
    await rm(directory, { recursive: true, force: true });
  }
  async abortMultipart(_key: string, uploadId: string) { await rm(this.partDir(uploadId), { recursive: true, force: true }); }
  async head(key: string) { try { return { size: (await stat(this.file(key))).size }; } catch { return undefined; } }
  async stream(key: string, _signal?: AbortSignal, start?: number) {
    const handle = await open(this.file(key)).catch(() => { throw new BridgeError('Объект источника не найден.', 404); });
    return handle.createReadStream({ start: start ?? 0 });
  }
  async delete(key: string) { await unlink(this.file(key)).catch((e: NodeJS.ErrnoException) => { if (e.code !== 'ENOENT') throw e; }); }
  async *list(prefix: string) {
    const walk = async function* (dir: string, rel: string): AsyncGenerator<{ key: string; size: number }> {
      for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
        if (entry.name.startsWith('.') ) continue;
        const next = rel ? rel + '/' + entry.name : entry.name;
        if (entry.isDirectory()) yield* walk(path.join(dir, entry.name), next);
        else if (entry.isFile() && !entry.name.endsWith('.tmp') && next.startsWith(prefix)) yield { key: next, size: (await stat(path.join(dir, entry.name))).size };
      }
    };
    yield* walk(this.root, '');
  }
  close() {}
}

export interface SourceStorageConfig { store?: SourceBlobStore; problem?: string; bucket?: string }
/** Source storage is configured separately from attachment storage (BRIDGE_S3_*). */
export function sourceStorageFromEnv(env: NodeJS.ProcessEnv): SourceStorageConfig {
  if (env.BRIDGE_SOURCES_STORAGE === 'filesystem') {
    if (env.NODE_ENV === 'production') return { problem: 'Локальное тестовое хранилище источников запрещено в production.' };
    if (!env.BRIDGE_SOURCES_DIR) return { problem: 'Для тестового хранилища укажите BRIDGE_SOURCES_DIR.' };
    return { store: new FilesystemSourceBlobStore(env.BRIDGE_SOURCES_DIR) };
  }
  const bucket = env.BRIDGE_SOURCES_S3_BUCKET;
  if (!bucket) return { problem: 'Хранилище источников не настроено.' };
  if (env.BRIDGE_S3_BUCKET && env.BRIDGE_S3_BUCKET === bucket) return { problem: 'Для источников нужен отдельный закрытый бакет, не бакет вложений.' };
  const accessKeyId = env.BRIDGE_SOURCES_S3_ACCESS_KEY;
  let secretAccessKey = env.BRIDGE_SOURCES_S3_SECRET_KEY;
  if (env.BRIDGE_SOURCES_S3_SECRET_KEY_FILE) {
    try { secretAccessKey = readFileSync(env.BRIDGE_SOURCES_S3_SECRET_KEY_FILE, 'utf8').trim(); }
    catch { return { problem: 'Не удалось прочитать файл ключа хранилища источников.' }; }
  }
  if (!accessKeyId || !secretAccessKey) return { problem: 'Для хранилища источников нужны ключи доступа.' };
  const endpoint = env.BRIDGE_SOURCES_S3_ENDPOINT || undefined;
  return { bucket, store: new S3SourceBlobStore(bucket, { endpoint, region: env.BRIDGE_SOURCES_S3_REGION || 'us-east-1', accessKeyId, secretAccessKey,
    forcePathStyle: !!endpoint && env.BRIDGE_SOURCES_S3_FORCE_PATH_STYLE !== '0' }, env.BRIDGE_SOURCES_S3_CREATE_BUCKET === '1') };
}
